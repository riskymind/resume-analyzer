"""Legacy fit analysis (``POST /api/analyze``) on top of deterministic job matching.

Before Milestone 4 the fit score was generated by the language model. It is
now the application-calculated match percentage from
``app.services.matching.engine``; this module only maps that report onto the
original response contract so the existing UI and history keep working.
"""

from __future__ import annotations

from app.schemas.legacy import AnalysisResult, Recommendations
from app.schemas.matching import MatchReport
from app.schemas.scoring import QualityReport

# Fixed score -> tier label thresholds (unchanged from the original app), checked from highest to lowest.
SCORE_THRESHOLDS: tuple[tuple[int, str], ...] = (
    (80, "Strong Match"),
    (60, "Good Match"),
    (40, "Fair Match"),
    (0, "Weak Match"),
)


def score_label(score: int) -> str:
    for threshold, label in SCORE_THRESHOLDS:
        if score >= threshold:
            return label
    return SCORE_THRESHOLDS[-1][1]


def legacy_result(report: MatchReport, quality: QualityReport | None) -> AnalysisResult:
    gaps = [
        f"{r.name}{'' if r.classification == 'required' else ' (preferred)'}"
        for r in report.requirements
        if r.status == "missing" and r.category != "responsibility"
    ]
    phrasing = [
        rec.message for rec in report.recommendations.top if rec.kind in ("present_better", "clarify_experience")
    ]
    formatting = [check.message for check in quality.ats_checks if not check.passed] if quality else []
    return AnalysisResult(
        score=report.match_score,
        score_label=score_label(report.match_score),
        recommendations=Recommendations(
            missing_keywords=list(report.keywords.missing),
            phrasing_suggestions=phrasing,
            skill_gaps=gaps,
            formatting_notes=formatting,
        ),
    )
