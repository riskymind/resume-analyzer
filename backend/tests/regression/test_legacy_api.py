@pytest.mark.parametrize(
    "response",
    [
        "not json",
        "",
        {"requirements": "not-a-list"},
        {"requirements": [{"category": "technical_skill"}]},
    ],
    ids=["malformed", "empty", "schema-violation", "missing-name"],
)
def test_bad_llm_output_returns_502(client: TestClient, fake_llm: FakeLLM, response) -> None:
    # Applies to the job-description extraction call that now precedes deterministic scoring.
    fake_llm.job_response = response
    res = analyze(client)
    assert res.status_code == 502
    assert "detail" in res.json()


