def test_history_list_and_detail(client: TestClient, fake_llm: FakeLLM) -> None:
    first = analyze(client).json()
    second = analyze(client, resume=("other.md", b"# Other\nPython", MD)).json()

    listing = client.get("/api/analyses")
    assert listing.status_code == 200
    items = listing.json()
    assert [item["id"] for item in items] == [second["id"], first["id"]]  # most recent first
    assert set(items[0]) >= {"id", "created_at", "resume_filename", "score", "score_label"}
    assert items[0]["score"] < items[1]["score"]  # a resume with almost no evidence scores lower
    assert items[0]["score_label"] == score_label(items[0]["score"])

    detail = client.get(f"/api/analyses/{first['id']}")
    assert detail.status_code == 200
    assert detail.json()["result"] == first["result"]
    assert detail.json()["jd_source"] == "pasted"


