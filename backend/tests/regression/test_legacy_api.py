"""Characterisation tests for the pre-refactor API (baseline commit ac8d085).

These pin the externally visible behaviour the existing frontend depends on:
paths, request fields, response shapes, status codes and the `detail` error
field. They must keep passing through the refactor; any intentional change to
this contract has to be made explicitly here.

Intentional contract change in Milestone 4: ``result.score`` is no longer
generated by the language model. It is the application-calculated job match
percentage (``app.services.matching.engine``); the response shape, the label
thresholds and the recommendation categories are unchanged.
"""

from __future__ import annotations

import pytest
from fastapi.testclient import TestClient

from app.services.fit_analysis import score_label
from tests.conftest import FakeLLM
from tests.fixtures.documents import SAMPLE_JD, SAMPLE_RESUME_MD, make_blank_pdf, make_pdf

MD = "text/markdown"
PDF = "application/pdf"
SAMPLE_RESUME_BYTES = SAMPLE_RESUME_MD.encode()


def analyze(client: TestClient, *, resume=("resume.md", SAMPLE_RESUME_BYTES, MD), jd_text=SAMPLE_JD, jd_file=None):
    files = {"resume": resume}
    data = {}
    if jd_text is not None:
        data["jd_text"] = jd_text
    if jd_file is not None:
        files["jd_file"] = jd_file
    return client.post("/api/analyze", files=files, data=data)


def test_health(client: TestClient) -> None:
    res = client.get("/api/health")
    assert res.status_code == 200
    assert res.json()["status"] == "ok"


def test_analyze_markdown_with_pasted_jd(client: TestClient) -> None:
    res = analyze(client)
    assert res.status_code == 200, res.text
    body = res.json()
    assert isinstance(body["id"], int)
    assert body["resume_filename"] == "resume.md"
    assert body["jd_source"] == "pasted"
    assert body["created_at"]
    result = body["result"]
    # Deterministic: every mandatory requirement of SAMPLE_JD is evidenced; of the preferred skills,
    # Terraform is missing and GCP is only related (AWS). See docs/job-matching-methodology.md, example 1.
    assert result["score"] == 85
    assert result["score_label"] == "Strong Match"
    assert body["job_match_id"]
    assert set(result["recommendations"]) == {
        "missing_keywords",
        "phrasing_suggestions",
        "skill_gaps",
        "formatting_notes",
    }
    assert result["recommendations"]["missing_keywords"] == ["Terraform", "GCP"]
    assert result["recommendations"]["skill_gaps"] == ["Terraform (preferred)"]


def test_analyze_pdf_resume(client: TestClient) -> None:
    res = analyze(client, resume=("cv.pdf", make_pdf(SAMPLE_RESUME_MD), PDF))
    assert res.status_code == 200, res.text
    assert res.json()["resume_filename"] == "cv.pdf"


def test_pdf_with_almost_no_text_is_rejected_as_scanned(client: TestClient) -> None:
    """Contract change in Milestone 3: PDFs with almost no text layer (scans) are rejected.

    Before Milestone 3 a PDF containing any text at all was accepted; a scanned
    resume with only a page number in its text layer was "analysed" as empty.
    """

    res = analyze(client, resume=("scan.pdf", make_pdf("Page 1"), PDF))
    assert res.status_code == 400
    assert "scanned or image-only" in res.json()["detail"]


