import { useState, type SyntheticEvent } from 'react'
import { fetchMatch } from '../api/jobs'
import type { AnalysisRecord, MatchDetail } from '../types/api'
import { formatDateTime } from '../utils/format'
import MatchReport from './MatchReport'
import QualityReport from './QualityReport'
import ScoreSeal from './ui/ScoreSeal'

type MatchState =
  | { status: 'idle' | 'loading'; match: null; error: null }
  | { status: 'success'; match: MatchDetail; error: null }
  | { status: 'error'; match: null; error: string }

/** Loads the full deterministic match report behind a fit score (analyses created since Milestone 4). */
function FullMatchReport({ matchId }: { matchId: string }) {
  const [state, setState] = useState<MatchState>({ status: 'idle', match: null, error: null })

  async function load(event: SyntheticEvent<HTMLDetailsElement>) {
    if (!event.currentTarget.open || state.status !== 'idle') return
    setState({ status: 'loading', match: null, error: null })
    try {
      setState({ status: 'success', match: await fetchMatch(matchId), error: null })
    } catch (err) {
      setState({ status: 'error', match: null, error: (err as Error).message })
    }
  }

  return (
    <details className="extracted" onToggle={load}>
      <summary>Full match report: requirements, evidence and score breakdown</summary>
      {state.status === 'loading' && (
        <p className="empty-note" role="status">
          Loading…
        </p>
      )}
      {state.status === 'error' && (
        <p className="form-flag" role="alert">
          <span>{state.error}</span>
        </p>
      )}
      {state.match && <MatchReport match={state.match} />}
    </details>
  )
}

const CATEGORY_LABELS: Record<keyof AnalysisRecord['result']['recommendations'], string> = {
  missing_keywords: 'Missing keywords',
  phrasing_suggestions: 'Phrasing suggestions',
  skill_gaps: 'Skill gaps',
  formatting_notes: 'Formatting notes',
}

/** Renders a fitment score and its recommendation categories for one analysis record. */
export default function AnalysisReport({ record }: { record: AnalysisRecord }) {
  const { result, resume_filename: resumeFilename, jd_source: jdSource, created_at: createdAt } = record

  return (
    <section>
      <div className="report-head">
        <ScoreSeal score={result.score} label="Job fit" />
        <div className="report-head-text">
          <h2>{result.score_label}</h2>
          <p className="report-meta">
            {resumeFilename} vs. {jdSource === 'pasted' ? 'pasted job description' : jdSource}
          </p>
        </div>
      </div>

      {createdAt && <p className="report-source">Reviewed {formatDateTime(createdAt)}</p>}
      {record.job_match_id ? (
        <p className="quality-intro">
          The match score is calculated by fixed rules from requirements quoted in the job description and evidence in
          your resume; it is not generated by AI.
        </p>
      ) : (
        <p className="quality-intro">This review was created before deterministic matching; its score came from AI.</p>
      )}

      {(Object.keys(CATEGORY_LABELS) as (keyof typeof CATEGORY_LABELS)[]).map((key) => {
        const label = CATEGORY_LABELS[key]
        const items = result.recommendations[key] ?? []
        return (
          <div key={key} className="report-row">
            <h3>{label}</h3>
            {items.length > 0 ? (
              <ul>
                {items.map((item, index) => (
                  <li key={index}>{item}</li>
                ))}
              </ul>
            ) : (
              <p className="none">None</p>
            )}
          </div>
        )
      })}

      {record.job_match_id && <FullMatchReport matchId={record.job_match_id} />}

      {record.resume_quality && <QualityReport quality={record.resume_quality} resumeId={record.resume_id} />}
    </section>
  )
}
